/** Renders docs/audio/derivatives.md from a `make audio` run. The output carries no timestamps. */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CUES, type CueSpec, LIMITS, MASTER_TRUE_PEAK_CEILING } from './contract.ts';
import {
  displayVersion,
  FFMPEG_PIN,
  type FfmpegVersion,
  type Loudness,
  METER_CHAIN,
  SAMPLE_RATE,
} from './ffmpeg.ts';

export interface FileRecord extends Loudness {
  name: string;
  bytes: number;
  sha256: string;
  /** SHA-256 of the decoded float PCM, so a decoder change shows apart from an encoder change. */
  pcmSha256: string;
}

export interface CueRecord {
  spec: CueSpec;
  sourceFrames: number;
  /** The hashed source as measured; `foldLossDb` only for mono cues. */
  source: Loudness & { foldLossDb: number | null };
  frames: number;
  gainDb: number;
  peakLimited: boolean;
  staged: Loudness;
  stageSha256: string;
  master: Loudness & { sha256: string };
  files: Record<'ogg' | 'mp3', FileRecord>;
  commands: Record<'stage' | 'gain' | 'ogg' | 'mp3', string[]>;
}

const fx = (value: number, digits = 2) => value.toFixed(digits);

export const CONTRACT_HASH_LABEL = 'Contract SHA-256';

/** Every file whose text decides the mastered bytes, relative to the repository root. */
const CONTRACT_FILES = [
  'scripts/audio/contract.ts',
  'scripts/audio/master-lib.ts',
  'scripts/audio/master.ts',
  'scripts/audio/ffmpeg.ts',
] as const;

/**
 * SHA-256 over the mastering contract and code. The validator compares it with the value in
 * derivatives.md, so a retuned contract without a `make audio` run fails without needing the
 * pinned FFmpeg.
 */
export function contractHash(root: string): string {
  const hash = createHash('sha256');
  for (const file of CONTRACT_FILES) hash.update(file).update(readFileSync(join(root, file)));
  return hash.digest('hex');
}

function shellQuote(arg: string): string {
  return /^[A-Za-z0-9_./:=+-]+$/.test(arg) ? arg : `'${arg.replace(/'/g, `'\\''`)}'`;
}

export function commandLine(args: readonly string[]): string {
  return ['ffmpeg', '-nostdin', '-hide_banner', ...args].map(shellQuote).join(' ');
}

function processing(spec: CueSpec, record: CueRecord): string {
  const parts: string[] = [];
  if (spec.channels === 1) parts.push('0.5L + 0.5R mono fold');
  const end = spec.trim.end === null ? 'source end' : `${spec.trim.end} s`;
  parts.push(`trim ${spec.trim.start} s to ${end}`);
  if (spec.loop) parts.push(`${spec.crossfade} s equal-power tail-to-head crossfade`);
  if (spec.fadeOut) parts.push(`${spec.fadeOut * 1000} ms fade-out`);
  if (spec.limiter)
    parts.push(`+${spec.limiter.preGainDb} dB into a ${spec.limiter.limit} limiter`);
  parts.push(
    `${record.gainDb >= 0 ? '+' : ''}${fx(record.gainDb)} dB gain${record.peakLimited ? ' (set by the true-peak ceiling)' : ''}`,
  );
  return parts.join(', ');
}

export function renderDerivatives(
  records: readonly CueRecord[],
  version: FfmpegVersion,
  contract: string,
): string {
  const total = records.reduce((sum, r) => sum + r.files.ogg.bytes + r.files.mp3.bytes, 0);
  const lines = [
    '# Audio runtime derivatives',
    '',
    'Generated by `make audio` (`scripts/audio/master.ts`). Do not edit by hand: `bun scripts/audio/master.ts --check` rebuilds every file into `build/audio/out/` and fails unless this page, `public/audio/manifest.json` and every runtime file come out byte-identical. The sources under `assets/audio/source/` are never written.',
    '',
    '## Toolchain',
    '',
    `- FFmpeg ${version.version}, libavcodec ${displayVersion(version.libavcodec ?? '')} (pin: ${FFMPEG_PIN.version}, libavcodec ${displayVersion(FFMPEG_PIN.libavcodec)}). Homebrew \`ffmpeg-full\`.`,
    `- libopus ${FFMPEG_PIN.libopus} and LAME ${FFMPEG_PIN.lame}, from \`brew list --versions opus lame\` on the mastering machine. FFmpeg does not report them, so only the rebuild check covers them.`,
    "- Every sample operation runs inside FFmpeg on 32-bit float audio at 48 kHz. Gains are computed from FFmpeg's own ebur128 measurement and rounded to 0.01 dB, so the same sources and the same build give the same bytes.",
    "- Ogg Opus uses output-scoped `-fflags +bitexact`, `-flags:a +bitexact` and a fixed `-serial_offset` per cue. MP3 keeps FFmpeg's normal `Lavc` gapless header, because the bitexact `Lavf` header is not trimmed by Firefox (see `~/.claude/guides/suno.md`).",
    '',
    `- ${CONTRACT_HASH_LABEL}: \`${contract}\` (${CONTRACT_FILES.map((f) => `\`${f}\``).join(', ')}). \`make asset-check\` fails when it no longer matches, on any FFmpeg.`,
    '',
    '## Method',
    '',
    "1. Stage: decode the source, resample to 48 kHz, fold SFX to mono by explicit 0.5L + 0.5R, trim, then apply the loop wrap or a one-shot fade-out. The loop wrap follows the Suno guide's tail-to-head rule: with the trimmed body b[0, M) and a crossfade of F frames, the loop is b[F, M-F) followed by b[M-F, M) fading out (quarter-cosine) under b[0, F) fading in (quarter-sine). Its last frame is b[F-1] at full gain, so the wrap lands on b[F] and the consumed intro is never replayed.",
    `2. Gain: an optional peak limiter (wind only), then one linear gain to the loudness target, cut back when the true peak would pass ${MASTER_TRUE_PEAK_CEILING} dBTP before encoding. This is the skill's measured post-normalisation trim; \`loudnorm\` is not used.`,
    '3. Encode Ogg Opus and MP3, decode both and remeasure. If either decoded true peak passes -1 dBTP, the gain drops by the overshoot plus 0.2 dB and the cue is re-encoded.',
    '',
    'Every loudness and true-peak value (the gain plan, the encoded re-measure and the validator) comes from this meter, reading the last `lavfi.r128.I` and `lavfi.r128.true_peak` values. For the gain plan of the limited cue, its limiter chain runs before `apad`:',
    '',
    '```sh',
    `${commandLine(['-v', 'error', '-i', 'FILE', '-map', '0:a:0', '-af', METER_CHAIN, '-f', 'null', '-'])}`,
    '```',
    '',
    'Targets (plans/phase-6-audio.md): music -18 LUFS ±1, stereo, 120-180 s loop, at most 3 MiB per file. SFX beds -24 LUFS ±2, mono, at most 512 KiB per file. True peak at most -1 dBTP after encoding. The plan sets the -24 LUFS target for SFX beds only. The one-shots (church-bell, portal-whoosh, stroke-rustle) use the same target as a newly proposed value, so the mixer can set their relative levels by gain.',
    '',
    '## Deviations pending the owner',
    '',
    'Each cue below misses a contract limit on purpose. `make asset-check` passes it with a named `WARN` until Paul decides. See `docs/audio/provenance.md`.',
    '',
    ...CUES.flatMap((c) =>
      (c.deviations ?? []).map(
        (d) =>
          `- \`${c.id}\` (${d.kind}, ${d.status}): ${d.reason}${d.upToDb !== undefined ? ` Waived up to ${d.upToDb} dB.` : ''}`,
      ),
    ),
    '',
    '## Sources as measured',
    '',
    `The hashed source, before any processing. The fold loss is the 0.5L + 0.5R mono fold against the mean channel power, limit ${LIMITS.monoMaxLossDb} dB, for mono cues only.`,
    '',
    '| Cue | Source SHA-256 | Integrated (LUFS) | True peak (dBTP) | Fold loss (dB) |',
    '| --- | --- | --- | --- | --- |',
    ...records.map(
      (r) =>
        `| \`${r.spec.id}\` | \`${r.spec.source.sha256}\` | ${fx(r.source.integrated)} | ${fx(r.source.truePeak)} | ${r.source.foldLossDb === null ? '' : fx(r.source.foldLossDb)} |`,
    ),
    '',
    '## Cues',
    '',
    '| Cue | Loop | Source | Processing | Frames | Duration | Stage SHA-256 | Master SHA-256 (build/audio/, not committed) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const r of records) {
    lines.push(
      `| \`${r.spec.id}\` | ${r.spec.loop ? 'loop' : 'one-shot'} | \`${r.spec.source.path}\` (${r.spec.source.sha256.slice(0, 12)}, ${r.sourceFrames} frames at 48 kHz) | ${processing(r.spec, r)} | ${r.frames} | ${fx(r.frames / SAMPLE_RATE, 3)} s | \`${r.stageSha256}\` | \`${r.master.sha256}\` |`,
    );
  }
  lines.push(
    '',
    '## Runtime files',
    '',
    'Loudness and true peak are measured on the decoded runtime file. `make asset-check` recomputes every value here from the current files (`scripts/audio/validate.ts`) instead of trusting this table.',
    '',
    '| File | Bytes | SHA-256 | Decoded PCM SHA-256 | Integrated (LUFS) | True peak (dBTP) |',
    '| --- | --- | --- | --- | --- | --- |',
  );
  for (const r of records) {
    lines.push(
      `| master \`${r.spec.id}\` | | | | ${fx(r.master.integrated)} | ${fx(r.master.truePeak)} |`,
    );
    for (const f of [r.files.ogg, r.files.mp3]) {
      lines.push(
        `| \`public/audio/${f.name}\` | ${f.bytes} | \`${f.sha256}\` | \`${f.pcmSha256}\` | ${fx(f.integrated)} | ${fx(f.truePeak)} |`,
      );
    }
  }
  lines.push(
    '',
    `Total runtime size: ${total} bytes (${fx(total / (1024 * 1024))} MiB).`,
    '',
    '## Commands',
    '',
  );
  lines.push('Run from the repository root, in this order per cue.', '');
  for (const r of records) {
    lines.push(`### ${r.spec.id}`, '', '```sh');
    for (const key of ['stage', 'gain', 'ogg', 'mp3'] as const)
      lines.push(commandLine(r.commands[key]));
    lines.push('```', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}
